import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';

const base = process.env.VIEWER_SMOKE_URL || 'http://127.0.0.1:8765';
const shots = process.env.VIEWER_SMOKE_SCREENSHOTS;
if (shots) await mkdir(shots, { recursive: true });
const browser = await chromium.launch();
try {
  for (const locale of ['en', 'zh-Hant']) for (const width of [1280, 390]) {
    const context = await browser.newContext({ viewport: { width, height: 900 } });
    const page = await context.newPage();
    page.setDefaultTimeout(10000);
    const errors = [], fontRequests = new Set();
    page.on('pageerror', e => errors.push(e.message));
    page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
    page.on('request', request => {
      const url = new URL(request.url());
      assert.ok(!/fonts\.(googleapis|gstatic)\.com/.test(url.hostname), 'No remote font requests');
      if (url.pathname.endsWith('.woff2')) fontRequests.add(url.pathname);
    });
    await context.route(url => url.pathname.startsWith('/api/'), route => route.fulfill({ json: { ok: true, data: { user: { sub: 'fixture' }, items: [] } } }));
    await page.goto(base + '/server/editor/index.html');
    await page.waitForFunction(() => window.editorSession);
    await page.evaluate(async locale => (await import('/server/app/i18n/index.js')).setLocale(locale), locale);
    await page.reload();
    await page.waitForFunction(() => window.editorSession);
    const field = page.locator('#editor-block-editor');
    await field.fill('## 香港學習\n**重點**');
    assert.equal(await page.locator('.block-select__title').first().innerText(), '香港學習 重點');
    await field.fill('\\# 是井號，\\* 是星號');
    assert.equal(await page.locator('.block-select__title').first().innerText(), '# 是井號，* 是星號');
    await page.evaluate(() => { window.editorSession.createBlock('question'); window.editorSession.notifyStateChange(); });
    await field.fill('如果顧客只說：「我要咖啡。」你會怎樣做？\n**重要**');
    assert.equal(await page.locator('label[for="editor-block-editor"]').innerText(), locale === 'en' ? 'Question text' : '題目文字');
    const preview = page.locator('.editor-text-preview-toggle');
    const edit = page.locator('.editor-text-edit-toggle');
    assert.equal(await edit.getAttribute('aria-pressed'), 'true');
    await preview.click();
    assert.equal(await preview.getAttribute('aria-pressed'), 'true');
    await preview.click();
    assert.equal(await field.isVisible(), false, 'Selected mode does not toggle off');
    await page.locator('.editor-text-help summary').click();
    assert.equal(await page.locator('.editor-text-help summary svg').count(), 1);
    assert.equal(await page.locator('.editor-text-help tbody tr').count(), 7);
    assert.equal(await page.locator('.editor-text-help tbody tr').last().locator('td').last().innerText(), '*');
    await page.evaluate(() => document.fonts.ready);
    if (shots) await page.screenshot({ path: `${shots}/polish-help-${locale}-${width}.png`, fullPage: true });
    await page.keyboard.press('Escape');
    await edit.click();
    const before = await page.evaluate(() => ({ draft: window.editorSession.state.draft.localId, block: window.editorSession.state.selectedBlockId }));
    const openLabel = await page.evaluate(async () => (await import('/server/app/i18n/index.js')).t('editor.actions.openViewer'));
    await page.getByRole('button', { name: openLabel, exact: true }).click();
    await page.locator('.viewer-back-to-editor').waitFor();
    const next = await page.evaluate(async () => (await import('/server/app/i18n/index.js')).t('viewer.actions.nextBlock'));
    await page.getByRole('button', { name: next, exact: true }).click();
    await page.locator('.question-card__prompt-label').waitFor();
    await page.locator('.question-card').evaluate(async el => { await Promise.all(el.getAnimations().map(a => a.finished)); });
    await page.evaluate(() => document.fonts.ready);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), true, 'Viewer header fits narrow screens');
    await page.evaluate(() => {
      const sample = document.createElement('span'); sample.id = 'font-test'; sample.textContent = '香港文字'; document.body.append(sample);
    });
    await page.evaluate(() => document.fonts.ready);
    const cdp = await context.newCDPSession(page);
    await cdp.send('DOM.enable'); await cdp.send('CSS.enable');
    const { root } = await cdp.send('DOM.getDocument');
    const { nodeId } = await cdp.send('DOM.querySelector', { nodeId: root.nodeId, selector: '#font-test' });
    const chinese = await cdp.send('CSS.getPlatformFontsForNode', { nodeId });
    assert.ok(chinese.fonts.some(font => font.isCustomFont && /Noto Sans HK/.test(font.familyName)), 'Chinese uses the bundled HK font');
    await page.locator('#font-test').evaluate(el => { el.textContent = 'English text 123'; });
    const latin = await cdp.send('CSS.getPlatformFontsForNode', { nodeId });
    assert.ok(latin.fonts.every(font => !/Noto Sans HK/.test(font.familyName)), 'Latin keeps its original font');
    await page.locator('#font-test').evaluate(el => el.remove());
    await cdp.detach();
    if (shots) await page.screenshot({ path: `${shots}/polish-viewer-${locale}-${width}.png`, fullPage: true });
    assert.ok(fontRequests.size > 0 && fontRequests.size < 99, 'Only required font subsets load');
    await page.reload();
    await page.locator('.viewer-back-to-editor').waitFor();
    const answer = page.locator('.question-card textarea').first();
    if (!await answer.isVisible()) await page.getByRole('button', { name: next, exact: true }).click();
    await answer.waitFor();
    await page.evaluate(() => {
      window.originalFlush = window.viewerSession.flushLocalStateForAuthRedirect.bind(window.viewerSession);
      window.flushCalls = 0;
      window.viewerSession.flushLocalStateForAuthRedirect = async () => {
        window.flushCalls++;
        await new Promise((resolve, reject) => { window.rejectReturnSave = reject; });
      };
    });
    await answer.fill('Preview answer before return');
    await page.locator('.viewer-back-to-editor').click();
    await page.waitForFunction(() => window.flushCalls === 1);
    assert.equal(await page.locator('.viewer-back-to-editor').isDisabled(), true);
    await page.locator('.viewer-back-to-editor').evaluate(el => el.click());
    assert.equal(await page.evaluate(() => window.flushCalls), 1, 'Repeated activation cannot duplicate a pending return');
    await page.evaluate(() => window.rejectReturnSave(new Error('Simulated storage failure')));
    await page.getByRole('alert').filter({ hasText: locale === 'en' ? 'could not be saved' : '未能儲存預覽作答' }).waitFor();
    assert.ok(page.url().includes('/viewer/'), 'Save failure stays in viewer');
    assert.equal(await answer.inputValue(), 'Preview answer before return');
    await page.evaluate(() => { window.viewerSession.flushLocalStateForAuthRedirect = window.originalFlush; });
    const attemptId = await page.evaluate(() => window.viewerSession.state.localAttemptId);
    await answer.fill('Latest answer immediately before return');
    await page.locator('.viewer-back-to-editor').click();
    await page.waitForFunction(() => window.editorSession);
    const stored = await page.evaluate(async id => (await import('/server/viewer/storage/index.js')).viewerStorage.attempts.get(id), attemptId);
    assert.ok(Object.values(stored.answers).some(answer => answer.value === 'Latest answer immediately before return'), 'Return flushes the debounce before navigating');
    assert.deepEqual(await page.evaluate(() => ({ draft: window.editorSession.state.draft.localId, block: window.editorSession.state.selectedBlockId })), before);
    assert.match(await field.inputValue(), /我要咖啡/);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), true);
    await page.goto(base + '/server/viewer/index.html');
    assert.equal(await page.locator('.viewer-back-to-editor').count(), 0, 'Ordinary learner entry has no editor action');
    assert.deepEqual(errors, []);
    console.log(`PASS ${locale} ${width}px: toggle, help, snippets, return after reload, local font subsets (${fontRequests.size})`);
    await context.close();
  }
} finally { await browser.close(); }
