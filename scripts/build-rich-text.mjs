import { build } from 'esbuild';
import { readFile, writeFile, readdir } from 'node:fs/promises';
import { gzipSync } from 'node:zlib';
const result = await build({ entryPoints: ['server/editor/rich-text-engine.js'], bundle: true, minify: true,
  format: 'esm', target: 'es2022', legalComments: 'eof', write: false, metafile: true });
const output = result.outputFiles[0].contents;
const packages = [...new Set(Object.keys(result.metafile.inputs).filter(path => path.startsWith('node_modules/')).map(path => {
  const parts = path.split('/'); return parts.slice(0, parts[1].startsWith('@') ? 3 : 2).join('/');
}))].sort();
let notices = '# Bundled rich-text editor notices\n\nGenerated by `npm run build:editor` from the packages included in the browser bundle.\nThe editor uses these open-source packages locally; no CDN or hosted editor service is required.\n';
for (const root of packages) {
  const pkg = JSON.parse(await readFile(`${root}/package.json`, 'utf8'));
  const files = (await readdir(root)).filter(file => /^(licen[sc]e|copying)(\.|$)/i.test(file)).sort();
  if (!files.length) throw new Error(`Missing license for ${pkg.name}`);
  notices += `\n## ${pkg.name} ${pkg.version} (${pkg.license})\n\n`;
  for (const file of files) notices += `${await readFile(`${root}/${file}`, 'utf8')}\n`;
}
for (const [path, data] of [['server/editor/vendor/rich-text-engine.js', output], ['server/editor/vendor/THIRD-PARTY-NOTICES.md', notices]]) {
  if (process.argv.includes('--check')) {
    if (!Buffer.from(await readFile(path)).equals(Buffer.from(data))) throw new Error('Rebuild the rich-text bundle with npm run build:editor');
  } else await writeFile(path, data);
}
console.log(`Editor engine: ${output.length} bytes; gzip ${gzipSync(output).length} bytes. Viewer loads none of this bundle.`);
